import sys, re
p=sys.argv[1]; s=open(p).read()
# 删掉之前所有 &pcie0 / &pcie0_phy 覆盖
s = re.sub(r"\n&pcie0 \{.*?\n\};\n", "\n", s, flags=re.S)
s = re.sub(r"\n&pcie0_phy \{.*?\n\};\n", "\n", s, flags=re.S)
